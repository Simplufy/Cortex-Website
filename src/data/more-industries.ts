type ExtraIndustry = {
  slug: string;
  href: string;
  name: string;
  blurb: string;
  hero: [string, string];
  intro: string;
  quote: string;
  symptoms: { title: string; body: string }[];
  systems: { title: string; body: string; items: string[] }[];
  software: { intro: string; groups: { title: string; tools: string[] }[] };
};

function trade(
  slug: string,
  name: string,
  noun: string,
  blurb: string,
  intro: string,
  quote: string,
  symptoms: [string, string][],
  systems: { title: string; body: string; items: string[] }[],
  softwareIntro: string,
  groups: { title: string; tools: string[] }[],
): ExtraIndustry {
  return {
    slug,
    href: `/industries/${slug}`,
    name,
    blurb,
    hero: [
      `You don't have to learn how to use AI in ${noun}.`,
      "See how we implement it across operations, marketing, and sales.",
    ],
    intro,
    quote,
    symptoms: symptoms.map(([title, body]) => ({ title, body })),
    systems,
    software: { intro: softwareIntro, groups },
  };
}

